// generateIPv4List 对每个 /24 子网取 sample 个随机 IP
func generateIPv4List(sample int) []string {
    if sample <= 0 {
        return []string{}
    }
    var ips []string
    for _, cidr := range cfIPv4CIDRs {
        _, ipnet, err := net.ParseCIDR(cidr)
        if err != nil {
            continue
        }
        ones, bits := ipnet.Mask.Size()
        if bits != 32 {
            continue
        }
        if ones >= 24 {
            // 对于 /24 或更小的子网（如 /25），直接使用该子网
            // 但由于我们的列表最小是 /22，实际上不会出现 ones > 24 的情况（除了 /24 本身）
            // 这里为了兼容，如果 ones == 24，直接取，如果 ones > 24，也直接取（因为不能再拆分成 /24）
            for i := 0; i < sample; i++ {
                ip := randomIP(ipnet)
                if ip != "" {
                    ips = append(ips, ip)
                }
            }
        } else {
            // 需要拆分成多个 /24 子网
            networkUint := ipToUint32(ipnet.IP)
            subnetsCount := 1 << (24 - ones)
            for j := 0; j < subnetsCount; j++ {
                subnetNetwork := networkUint + uint32(j<<(32-24))
                subnetIP := uint32ToIP(subnetNetwork)
                subnetNet := &net.IPNet{
                    IP:   subnetIP,
                    Mask: net.CIDRMask(24, 32),
                }
                for i := 0; i < sample; i++ {
                    ip := randomIP(subnetNet)
                    if ip != "" {
                        ips = append(ips, ip)
                    }
                }
            }
        }
    }
    return ips
}

