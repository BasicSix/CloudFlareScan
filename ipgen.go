// randomIP 通用随机 IP 生成（支持 IPv4 和 IPv6）
func randomIP(ipnet *net.IPNet) string {
    ip := ipnet.IP
    var length int
    if ip.To4() != nil {
        ip = ip.To4()
        length = 4
    } else {
        ip = ip.To16()
        length = 16
    }
    if ip == nil {
        return ""
    }
    mask := ipnet.Mask
    result := make([]byte, length)
    for i := 0; i < length; i++ {
        result[i] = ip[i]&mask[i] | byte(rand.Intn(256))&^mask[i]
    }
    // 避免网络地址（主机位全 0）
    isNetwork := true
    for i := 0; i < length; i++ {
        if result[i] != (ip[i] & mask[i]) {
            isNetwork = false
            break
        }
    }
    if isNetwork {
        for i := length - 1; i >= 0; i-- {
            result[i]++
            if result[i] != 0 {
                break
            }
        }
    }
    return net.IP(result).String()
}

// 辅助函数：IPv4 地址与 uint32 互转（用于 /24 拆分）
func ipToUint32(ip net.IP) uint32 {
    ip = ip.To4()
    if ip == nil {
        return 0
    }
    return uint32(ip[0])<<24 | uint32(ip[1])<<16 | uint32(ip[2])<<8 | uint32(ip[3])
}

func uint32ToIP(n uint32) net.IP {
    return net.IPv4(byte(n>>24), byte(n>>16), byte(n>>8), byte(n))
}